"""Render fold skill and seed sensitivity from completed reports; no model fitting."""
from pathlib import Path
import csv
import json
import statistics

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT/'thesis/generated'
OUT = ROOT/'analysis/graph_2026_10/out/thesis_sizing20x'


def main():
    from thesis_nba_decay import main as nba_decay
    nba_decay()
    rows, audit = [], []
    for league, delay, suffix in [('MLB', 10, '_pitch'), ('NBA', 60, ''), ('NFL', 60, '')]:
        reports = {(fold, seed): json.loads((ROOT/'results/ingame'/
                   f'{league}_fold{fold}_gru_d{delay}_h30-60-120-1800_tp{suffix}_seed{seed}.json').read_text())
                   for fold in range(1, 6) for seed in range(5)}
        for kind in ('spread', 'total'):
            for horizon in ('30s', '60s', '120s'):
                values = []
                for fold in range(1, 6):
                    value = statistics.mean(100*reports[fold, seed]['metrics'][kind][horizon]['r2_model']
                                            for seed in range(5))
                    values.append(value)
                    audit.append(dict(league=league, kind=kind, horizon=horizon, fold=fold,
                                      delay_s=delay, mean_seed_skill_pct=value))
                rows.append(' & '.join([league, kind.capitalize(), horizon.replace('s', ''),
                                        *[f'{v:.2f}' for v in values]])+r'\\')
    (GEN/'fold_skill.tex').write_text(r'''% Generated by thesis_supplementary.py.
\begin{table}[htbp]\centering\small
\caption{Forecast Skill by Development Fold}
\label{tab:fold-skill}
\begin{tabular}{@{}lllrrrrr@{}}\toprule
League & Contract & Horizon (s) & Fold 1 & Fold 2 & Fold 3 & Fold 4 & Fold 5\\\midrule
'''+ '\n'.join(rows)+r'''
\bottomrule\end{tabular}
\tablenote{Skill against no change (\%), averaged over five seeds. Feed delays: MLB 10 s; NBA/NFL 60 s.}
\end{table}
''')
    with (OUT/'fold_skill.csv').open('w') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(audit[0]))
        writer.writeheader(); writer.writerows(audit)
    with (OUT/'holdout_summary.csv').open() as stream:
        summary = list(csv.DictReader(stream))
    rows = []
    for league in ('MLB', 'NFL'):
        for kind in ('spread', 'total'):
            selected = [r for r in summary if r['league'] == league and r['kind'] == kind
                        and r['source'] in [f'seed{s}' for s in range(5)] and r['horizon'] == '120s']
            assert len(selected) == 5
            returns = [float(r['net_c']) for r in selected]
            ensemble = next(r for r in summary if r['league'] == league and r['kind'] == kind
                            and r['source'] == 'full model (frozen)' and r['horizon'] == '120s')
            rows.append(f"{league} & {kind.capitalize()} & {min(returns):.2f} & {max(returns):.2f} & {float(ensemble['net_c']):.2f}"+r'\\')
    (GEN/'seed_returns.tex').write_text(r'''% Generated by thesis_supplementary.py.
\begin{table}[htbp]\centering\small
\caption{Out-of-Sample Returns Across Random Seeds}
\label{tab:seed-returns}
\begin{tabular}{@{}llrrr@{}}\toprule
League & Contract & Lowest seed & Highest seed & Ensemble\\\midrule
'''+ '\n'.join(rows)+r'''
\bottomrule\end{tabular}
\tablenote{Net cents per contract at $20\times$ sizing. Seed ranges are descriptive. NFL uses the revised five-second decision interval.}
\end{table}
''')


if __name__ == '__main__':
    main()
