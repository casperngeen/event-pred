"""Describe signal/width returns in unfiltered development fills; no holdout reads.

Orders use forecast direction but no signal-magnitude cutoff or sizing weights.
Each saved fill receives equal weight. These are descriptive comparison returns,
not the sized strategy's performance or a sizing optimisation.
"""
from pathlib import Path

import polars as pl

HERE = Path(__file__).resolve().parent
DATA = HERE / "out/thesis_sizing20x"
GEN = HERE.parents[1] / "thesis/generated"


def main():
    import json

    frames, sources = [], {}
    for league, delay in (("MLB", 10), ("NBA", 60), ("NFL", 60)):
        paths = sorted((HERE / "out/thesis_unfiltered_signals").glob(f"{league}_fold[1-5].parquet"))
        assert len(paths) == 5, (league, paths)
        audits = [json.loads(path.with_suffix(".json").read_text()) for path in paths]
        assert all(a["parity"] == "exact" and a["min_signal"] == 0 for a in audits)
        raw = pl.concat([pl.read_parquet(path) for path in paths], how="vertical_relaxed")
        raw = raw.filter(pl.col("k") == 1, pl.col("through") == 0,
                         pl.col("hold") == "120s", pl.col("kind").is_in(("spread", "total")))
        assert raw["fold"].min() > 0
        frame = raw.with_columns(pl.lit(league).alias("league"))
        frames.append(frame)
        sources[league] = dict(delay_s=delay, files=[str(path) for path in paths], fills=frame.height,
                               min_signal=0, sizing="one contract per fill comparison", audits=audits)
    fills = pl.concat(frames, how="diagonal_relaxed")
    assert (fills["signal"].abs() <= 5).any()
    columns = [(league, kind) for league in ("MLB", "NBA", "NFL") for kind in ("spread", "total")]
    specifications = [
        ("Signal", fills, pl.col("signal").abs(), [8, 10, 15],
         [r"$\leq8$", "8--10", "10--15", r"$\geq15$"]),
        ("Width", fills.filter(pl.col("width").is_not_null()), pl.col("width"), [5, 10],
         [r"$<5$", "5--10", r"$\geq10$"]),
    ]
    rows, audit = [], []
    for name, frame, value, edges, labels in specifications:
        if name == "Signal":
            frame = frame.with_columns(pl.when(value <= 8).then(pl.lit(r"$\leq8$"))
                                      .otherwise(value.cut(edges, labels=labels, left_closed=True)
                                                 .cast(pl.String)).alias("band"))
        else:
            frame = frame.with_columns(value.cut(edges, labels=labels, left_closed=True)
                                       .cast(pl.String).alias("band"))
        grouped = frame.group_by("league", "kind", "band").agg(
            pl.len().alias("fills"), pl.col("net").mean().alias("net_c"))
        assert grouped["fills"].sum() == frame.height
        for i, label in enumerate(labels):
            cells = []
            for league, kind in columns:
                found = grouped.filter(pl.col("league") == league, pl.col("kind") == kind,
                                       pl.col("band") == label)
                record = found.row(0, named=True) if found.height else dict(
                    league=league, kind=kind, band=label, fills=0, net_c=None)
                audit.append(dict(measure=name, **record))
                cells.append(f"{record['net_c']:.2f}" if record["fills"] else "---")
            rows.append(f"{name if i == 0 else ''} & {label} & "+" & ".join(cells)+r"\\")
        rows.append(r"\midrule")
    pl.DataFrame(audit).write_csv(DATA/"sizing_evidence.csv")
    (DATA/"sizing_evidence_sources.json").write_text(json.dumps(sources, indent=2)+"\n")
    text = r"""% Generated by thesis_sizing_evidence.py; do not edit.
\begin{table}[htbp]\centering\small
\caption{Returns by Signal Strength and Trading Width}
\label{tab:sizing-evidence}
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}llrrrrrr@{}}\toprule
 & & \multicolumn{2}{c}{MLB} & \multicolumn{2}{c}{NBA} & \multicolumn{2}{c}{NFL}\\
Measure & Band & Spread & Total & Spread & Total & Spread & Total\\\midrule
"""+"\n".join(rows[:-1])+r"""
\bottomrule\end{tabular}
\tablenote{One contract per fill, with no signal cutoff or sizing weights; 120 s exits. Feed delays: MLB 10 s; NBA/NFL 60 s. Bands are assigned after simulation. Returns are net cents per contract; missing widths are excluded from width bands.}
\end{table}
"""
    (GEN/"ch5_sizing_evidence.tex").write_text(text)


if __name__ == "__main__":
    main()
