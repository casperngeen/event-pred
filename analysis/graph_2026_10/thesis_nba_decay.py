"""Compare NBA development folds at the deployed 60-second feed delay."""
from pathlib import Path
import json
import polars as pl

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT/'analysis/graph_2026_10/out/thesis_sizing20x'
GEN = ROOT/'thesis/generated'


def main():
    fills = pl.read_parquet(DATA/'development_NBA.parquet').filter(
        pl.col('source') == 'delay 60 s', pl.col('hold') == '120s')
    assert fills.height > 0 and (fills['size'] > 0).all()
    grouped = fills.group_by('fold', 'kind').agg(
        pl.col('size').sum().alias('quantity'), pl.col('pnl').sum().alias('net_cents'))
    summary = pl.read_csv(DATA/'development_summary.csv').filter(
        pl.col('league') == 'NBA', pl.col('source') == 'delay 60 s',
        pl.col('horizon') == '120s')
    for kind in ('spread', 'total'):
        selected = grouped.filter(pl.col('kind') == kind)
        net = selected['net_cents'].sum()/selected['quantity'].sum()
        saved = summary.filter(pl.col('kind') == kind)['net_c'][0]
        assert abs(net-saved) < 1e-8
    audit, rows = [], []
    for fold in range(1, 6):
        path = ROOT/'results/ingame/ens5'/f'NBA_fold{fold}_gru_d60_h30-60-120-1800_tp_ens5_seed0.json'
        report = json.loads(path.read_text())
        assert report['delay_s'] == 60 and report['test_fold'] == fold
        row = []
        for kind in ('spread', 'total'):
            trade = grouped.filter(pl.col('fold') == fold, pl.col('kind') == kind).row(0, named=True)
            # average_seeds.py stores ensemble R2 in percentage points already.
            skill = report['r2_ens5'][kind]['120s']
            net = trade['net_cents']/trade['quantity']
            row.append((skill, net))
            audit.append(dict(fold=fold, kind=kind, skill_pct=skill,
                              net_c_per_contract=net, **{k:v for k,v in trade.items() if k not in ('fold','kind')}))
        rows.append(f'{fold} & {row[1][0]:.2f} & {row[1][1]:.2f}'+r'\\')          # totals only (the spread columns stay in nba_fold_comparison.csv)
    pl.DataFrame(audit).write_csv(DATA/'nba_fold_comparison.csv')
    (GEN/'nba_fold_comparison.tex').write_text(r'''% Generated by thesis_nba_decay.py.
\begin{table}[htbp]\centering\small
\caption{NBA Totals by Development Fold}
\label{tab:nba-fold-comparison}
\begin{tabular}{@{}lrr@{}}\toprule
Fold & Forecast skill (\%) & Net cents/contract\\\midrule
'''+ '\n'.join(rows)+r'''
\bottomrule\end{tabular}
\tablenote{Five-seed ensemble; 60 s feed delay and 120 s horizon/exit. Historical returns use $20\times$ quantities on saved fills.}
\end{table}
''')


if __name__ == '__main__':
    main()
