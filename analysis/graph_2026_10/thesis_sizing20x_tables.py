"""Render Chapter 5 tables/figure from thesis_sizing20x.py's audited summaries.

Run from the repository root after both development and original-holdout scoring.
No raw data, predictions, or replay selection are read or changed here.
"""
from pathlib import Path
import os
import tempfile

os.environ.setdefault("MPLCONFIGDIR",str(Path(tempfile.gettempdir())/"event_pred_matplotlib"))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
import polars as pl

HERE = Path(__file__).resolve().parent
DATA = HERE / "out/thesis_sizing20x"
GEN = HERE.parents[1] / "thesis/generated"
FULL = "full model (frozen)"
LEAGUES = ("MLB", "NBA", "NFL")
KINDS = ("spread", "total")


def get(frame, league, kind, source=FULL, horizon="120s"):
    result = frame.filter(pl.col("league")==league, pl.col("kind")==kind,
                          pl.col("source")==source, pl.col("horizon")==horizon)
    assert result.height == 1, (league, kind, source, horizon)
    return result.row(0, named=True)


def number(x, decimals=1):
    if abs(x) < 0.5 * 10**(-decimals):
        x = 0
    return f"{x:.{decimals}f}"


def write(name, text):
    (GEN/name).write_text("% Generated by thesis_sizing20x_tables.py; do not edit.\n"+text+"\n")


def main():
    from thesis_sizing_evidence import main as sizing_evidence
    sizing_evidence()
    dev = pl.read_csv(DATA/"development_summary.csv")
    hold = pl.read_csv(DATA/"holdout_summary.csv")
    rows = []
    for title, frame, leagues in (("Walk-forward test folds (development)",dev,LEAGUES),("Later historical out-of-sample period",hold,("MLB","NFL"))):
        rows.append(r"\multicolumn{7}{@{}l}{\emph{"+title+r"}}\\")
        for league in leagues:
            for kind in KINDS:
                r = get(frame,league,kind)
                rows.append(f"{league} {kind} & {r['games']} & {r['quantity']:,.0f}".replace(",",r"\,")+" & "+
                            " & ".join(number(r[k]) for k in ("gross_c","net_c","t_game"))+
                            f" & {r['fill_win_pct']:.0f}"+r"\\")
        rows.append(r"\midrule")
    text = r"""\begin{table}[htbp]\centering\small
\caption{Historical Trading Returns}
\label{tab:main-pnl}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{@{}lrrrrrr@{}}\toprule
Contract type & Games & Quantity & Gross & Net & $t$ & Fill win rate (\%)\\
\midrule
"""+"\n".join(rows[:-1])+r"""
\bottomrule\end{tabular}
\tablenote{Returns are cents per contract; net deducts fees. Quantities follow Section~\ref{sec:position-sizing}, retaining the saved entry and exit paths (Appendix~\ref{sec:historical-resizing}). Feed delays: MLB 10 s; NBA/NFL 60 s. Game-level $t$ includes zero-trade games; win rate counts profitable fills equally. Walk-forward results informed strategy selection. NBA has no later-period sample.}
\end{table}"""
    write("ch5_20x_main.tex",text)

    old = pl.read_csv(HERE/"out/b33_ablation_table.csv")
    order = [(l,k) for l in LEAGUES for k in KINDS]
    def skill(league,kind,version,column="r2_120s"):
        return old.filter(pl.col("contract")==f"{league} {kind}",pl.col("version")==version)[column][0]
    ensemble_gap=set()
    def skill_gap(league,kind,source,base):
        a,b = skill(league,kind,source), skill(league,kind,base)
        if a is None:       # versions averaged on the cluster keep only the five-seed ensemble score: compare ensemble scores
            ensemble_gap.add(league)
            a,b = skill(league,kind,source,"r2_ens"), skill(league,kind,base,"r2_ens")
        return a-b
    def texrow(label, cells):
        return label+" & "+" & ".join(cells)+r"\\"
    ab = [r"\midrule"]
    versions = [("No message passing","no graph (no message passing)"),
                ("No play memory","no play memory"),("Neither","neither (step and contract features only)"),
                ("No play type","no play types"),("No win probability","no win probability (and its baseline)"),
                ("No structural reference","no structural baseline"),("No recent trades","no recent trades / flow"),
                ("No quotes","no quotes")]
    draft=set()
    for label, source in versions:
        cells=[]
        for l,k in order:
            try:
                r=get(dev,l,k,source)
                full_delay=get(dev,l,k)["delay_s"]
                if r["delay_s"]!=full_delay:               # not yet trained at the league's delay: compared with the 10 s full model
                    draft.add(l); base="full model (10 s reference)"
                else:
                    base=FULL
                cells.append(f"{number(skill_gap(l,k,source,base))} ({number(r['paired_t_vs_full'])})")
            except (AssertionError,TypeError,IndexError):      # a version not (yet) trained at the league's delay
                cells.append("--")
        ab.append(texrow(label,cells))
    references = {l: "full model (10 s reference)" if l in draft else FULL for l in LEAGUES}
    # Differences for the leagues in ensemble_gap are ensemble scores, so the full-model row is the ensemble score there too.
    ab[:0] = [texrow(r"\emph{Full model: skill (\%)}", [number(skill(l,k,references[l],"r2_ens" if l in ensemble_gap else "r2_120s"),2) for l,k in order]),
              texrow(r"\emph{Full model: net c/unit}", [number(get(dev,l,k,references[l])["net_c"]) for l,k in order])]
    for _, source in versions:
        for l,k in order:
            row = dev.filter(pl.col("league")==l, pl.col("kind")==k,
                             pl.col("source")==source, pl.col("horizon")=="120s")
            if row.height:
                assert row["delay_s"][0] == get(dev,l,k,references[l])["delay_s"], "Ablation rows require matching reference delays"
    write("ch5_20x_ablation.tex",r"""\begin{table}[htbp]\centering\footnotesize
\caption{Model Ablation Results"""+(" (Provisional)" if draft else "")+r"""}
\label{tab:ablation}\setlength{\tabcolsep}{3pt}
\begin{tabular}{@{}lrrrrrr@{}}\toprule
 & MLB spread & MLB total & NBA spread & NBA total & NFL spread & NFL total\\\midrule
"""+"\n".join(ab)+r"""\bottomrule\end{tabular}\tablenote{Skill changes are percentage points; parentheses show paired profit $t$-statistics against the matched full model. Skill is the $R^2$ of the forecast at 120 seconds: for MLB the mean of the five single-seed scores, for NBA and NFL the score of the five-seed average forecast, which is also the basis of the changes in those columns.}
\end{table}""")
    # skill and net return by feed delay (separately trained models; from the ablation table's delay versions)
    delays=[0,5,10,15,30,45,60]
    operating={"MLB":10,"NBA":60,"NFL":60}
    def delay_version(l,d):
        if d==10: return FULL if l=="MLB" else "full model (10 s reference)"
        if d==60 and l!="MLB": return FULL
        return "delay 45 s (ESPN live)" if d==45 else f"delay {d} s"
    def delay_cell(l,k,d,column,decimals):
        rows_=old.filter(pl.col("contract")==f"{l} {k}",pl.col("version")==delay_version(l,d))
        if not rows_.height or rows_[column][0] is None:
            return "--"
        text=number(rows_[column][0],decimals)
        return r"\textbf{"+text+"}" if d==operating[l] else text
    panels=[]
    for title,column,decimals in (("Forecast skill at 120 s (\\%)","r2_120s",2),("Net cents per contract","net_c",1)):
        panels.append(r"\multicolumn{8}{@{}l}{\emph{"+title+r"}}\\")
        for l,k in order:
            panels.append(texrow(f"{l} {k}",[delay_cell(l,k,d,column,decimals) for d in delays]))
        panels.append(r"\midrule")
    write("ch5_20x_delay.tex",r"""\begin{table}[htbp]\centering\small
\caption{Forecast Skill and Net Return by Feed Delay}
\label{tab:feed-delay}
\begin{tabular}{@{}lrrrrrrr@{}}\toprule
Contract type & 0 s & 5 s & 10 s & 15 s & 30 s & 45 s & 60 s\\\midrule
"""+"\n".join(panels[:-1])+r"""
\bottomrule\end{tabular}
\tablenote{Each delay uses a separately trained model, with the same delay applied in evaluation; five-seed means on the development folds. Net returns are at $20\times$ sizing. Bold marks each league's operating delay (MLB 10 s; NBA and NFL 60 s); -- marks delays not trained.}
\end{table}""")
    hr=[]
    for l,k in order:
        short, medium, full = [get(dev,l,k,horizon=h) for h in ("30s","60s","120s")]
        cells=[number(r["net_c"],2) for r in (short,medium,full)]
        cells += [number(-short["paired_t_vs_full"]),number(-medium["paired_t_vs_full"])]
        hr.append(texrow(f"{l} {k}",cells))
    write("ch5_20x_horizons.tex",r"""\begin{table}[htbp]\centering\small
\caption{Returns by Forecast Horizon}
\label{tab:horizon-trading}
\begin{tabular}{@{}lrrrrr@{}}\toprule
 & \multicolumn{3}{c}{Net cents/unit} & \multicolumn{2}{c}{Paired $t$}\\
Contract type & 30 s & 60 s & 120 s & $120-30$ & $120-60$\\\midrule
"""+"\n".join(hr)+r"""\bottomrule\end{tabular}\tablenote{Development results at $20\times$ sizing; feed delay 10 s for MLB and 60 s for NBA and NFL. Paired $t$ compares game-level profit at 120 s with each shorter horizon, including zero-trade games.}
\end{table}""")

    b=[get(hold,"MLB",k) for k in KINDS]
    n=[get(hold,"NFL",k) for k in KINDS]
    def rate(r):
        return number(r["net_c"])+" cents per unit ($t="+number(r["t_game"])+"$)"
    prose=("In the later historical out-of-sample period, the strategy earns "+rate(b[0])+" on MLB spreads and "+rate(b[1])+" on MLB totals. "
           "Both remain below their development levels. NFL spreads earn "+rate(n[0])+", while totals earn "+rate(n[1])+". "
           "\n\n")
    original=[get(hold,"NFL",k,"original 60s decision grid") for k in KINDS]
    prose+=("The NFL figures use the five-second decision interval adopted after the first evaluation. "
            "Under the original 60-second grid, spreads earn "+rate(original[0])+" and totals "+rate(original[1])+". "
            "The comparison therefore remains subject to the protocol-change qualification in Chapter~\\ref{ch:data}.\n")
    write("ch5_20x_discussion.tex",prose)

    games=pl.concat([pl.read_parquet(DATA/f"{m}_per_game.parquet") for m in ("development","holdout")],how="vertical_relaxed").filter(pl.col("horizon")=="120s")
    plt.rcParams.update({"font.size":9,"axes.titlesize":10})
    fig,axes=plt.subplots(1,3,figsize=(7.2,3.0))
    for ax,l in zip(axes,LEAGUES):
        for k,color in zip(KINDS,("#33658a","#c46c35")):
            x=(games.filter(pl.col("league")==l,pl.col("kind")==k)
               .with_columns(pl.col("first_play").dt.convert_time_zone("America/New_York").dt.date().alias("day"))
               .group_by("day").agg(pl.col("pnl").sum()).sort("day"))
            dates=x["day"].to_list()
            ax.plot(dates,x["pnl"].cum_sum()/100,color=color,label=k.title())
        if l!="NBA":
            from datetime import date
            ax.axvspan(date(2026,7,1),max(dates),color="#999999",alpha=.12)
        ax.axhline(0,color="#777777",linewidth=.6)
        ax.set_title(l); ax.grid(axis="y",alpha=.2)
        ax.xaxis.set_major_locator(mdates.AutoDateLocator(minticks=3,maxticks=4))
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %Y"))
        ax.tick_params(axis="x",labelsize=8,rotation=25)
    axes[0].set_ylabel("Cumulative net profit (USD)")
    axes[0].legend(frameon=False,fontsize=8)
    fig.tight_layout()
    fig.savefig(GEN/"ch5_20x_cumulative.pdf",bbox_inches="tight")
    print("Rendered Chapter 5 tables and cumulative-profit figure")


if __name__=="__main__":
    main()
